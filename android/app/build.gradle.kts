// ── Rust core build integration ─────────────────────────────────────────────
// Automatically cross-compiles the Rust core and generates UniFFI bindings
// before Kotlin compilation. Debug builds target only arm64 for speed;
// release builds target all ABIs.

val coreDir = rootProject.file("../server/app-core")
val serverDir = rootProject.file("../server")
val uniffiCoreDir = serverDir.resolve("vendor/uniffi_core")
val buildCoreScript = rootProject.file("scripts/build-core.sh")
val jniLibsDir = file("src/main/jniLibs")

val isReleaseBuild =
    gradle.startParameter.taskNames.any {
        it.contains("Release", ignoreCase = true)
    }
val targetAbis = if (isReleaseBuild) listOf("arm64-v8a", "armeabi-v7a", "x86_64", "x86") else listOf("arm64-v8a")

tasks.register("buildRustCore") {
    description = "Cross-compile Rust core for Android and generate UniFFI bindings"
    inputs.dir(coreDir.resolve("src"))
    inputs.file(coreDir.resolve("Cargo.toml"))
    inputs.file(serverDir.resolve("Cargo.toml"))
    inputs.file(serverDir.resolve("Cargo.lock"))
    inputs.dir(serverDir.resolve("shared/src"))
    inputs.dir(uniffiCoreDir.resolve("src"))
    inputs.file(uniffiCoreDir.resolve("Cargo.toml"))
    inputs.file(buildCoreScript)
    inputs.property("targetAbis", targetAbis)
    outputs.dir(jniLibsDir)

    doLast {
        providers
            .exec {
                commandLine(listOf(buildCoreScript.absolutePath) + targetAbis)
            }.result
            .get()
    }
}

tasks
    .matching {
        (it.name.startsWith("compile") && it.name.contains("Kotlin")) ||
            it.name.startsWith("merge") &&
            it.name.contains("JniLibFolders")
    }.configureEach {
        dependsOn("buildRustCore")
    }

// Read config from the project root .env file (generated by `make setup-env`)
val envFile =
    rootProject.file("../.env").let { f ->
        mutableMapOf<String, String>().also { map ->
            if (f.exists()) {
                f.readLines().forEach { line ->
                    val trimmed = line.trim()
                    if (trimmed.isNotEmpty() && !trimmed.startsWith("#") && '=' in trimmed) {
                        val (k, v) = trimmed.split("=", limit = 2)
                        map[k.trim()] = v.trim()
                    }
                }
            }
        }
    }

val appEnv = project.findProperty("APP_ENV") as String? ?: envFile["APP_ENV"] ?: "dev"
val isProd = appEnv == "prod"

fun devIntSetting(name: String): String = ((project.findProperty(name) as String?) ?: envFile[name] ?: "-1").toInt().toString()

